import math

x = (13, 67, 18)
print("Maximum in x : ", max(x))

print("Minimum in x : ", min(x))

print("Average : ", (sum(x) / len(x)))

a = pow(2, 4)
print("2 raised to the power 4 : ", a)

b = math.sqrt(256)
print("Square root of 256 : ", b)

